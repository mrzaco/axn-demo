import { expect, test } from '@playwright/test';

test('定时任务可创建、编辑、暂停、恢复、删除并在刷新后保留', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('button', { name: '应急专家', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '定时任务', exact: true }).click();
  await page.getByRole('button', { name: '新建定时任务', exact: true }).click();
  const modal = page.getByRole('dialog');
  await modal.getByLabel('任务名称', { exact: true }).fill('每周资源核对');
  await expect(modal.getByText('请选择智能体（选填）', { exact: true })).toBeVisible();
  await modal.getByLabel('执行智能体（选填）', { exact: true }).click();
  await expect(page.getByRole('option')).toHaveCount(5);
  await page.getByRole('option', { name: '救援资源管理智能体', exact: true }).click();
  await modal.getByLabel('执行内容', { exact: true }).fill('查询周边救援资源');
  await modal.getByLabel('重复周期', { exact: true }).click();
  await page.getByRole('option', { name: '每周', exact: true }).click();
  await modal.getByLabel('执行日', { exact: true }).click();
  await page.getByRole('option', { name: '周二', exact: true }).click();
  await modal.getByLabel('执行时间（北京时间）', { exact: true }).fill('09:30');
  await modal.getByRole('button', { name: '保存任务', exact: true }).click();
  let card = page.locator('.axn-schedule-card', { hasText: '每周资源核对' });
  await expect(card).toContainText('每周二 09:30');
  await expect(card).toContainText('智能体：救援资源管理智能体');
  await card.getByRole('switch', { name: '启用每周资源核对', exact: true }).click();
  await expect(card).toContainText('已暂停');
  await page.reload();
  await expect(card).toContainText('已暂停');
  await expect(card).toContainText('智能体：救援资源管理智能体');
  await card.getByRole('switch', { name: '启用每周资源核对', exact: true }).click();
  await expect(card.getByRole('switch')).toBeChecked();
  await card.getByRole('button', { name: '编辑每周资源核对', exact: true }).click();
  await expect(page.getByRole('dialog').getByLabel('执行智能体（选填）', { exact: true })).toHaveAttribute('aria-expanded', 'false');
  await expect(page.getByRole('dialog')).toContainText('救援资源管理智能体');
  await page.getByRole('dialog').getByLabel('任务名称', { exact: true }).fill('每周资源复核');
  await page.getByRole('dialog').getByRole('button', { name: '保存任务', exact: true }).click();
  card = page.locator('.axn-schedule-card', { hasText: '每周资源复核' });
  await expect(card).toBeVisible();
  await card.getByRole('button', { name: '删除每周资源复核', exact: true }).click();
  await page.getByRole('button', { name: /^删\s*除$/ }).click();
  await expect(card).toHaveCount(0);
});

test('定时任务模拟执行产生结果对话与文件', async ({ page }) => {
  await page.goto('/#/schedules');
  const cards = page.locator('.axn-schedule-card');
  await expect(cards).toHaveCount(3);
  const bounds = await cards.evaluateAll(elements => elements.map(el => {
    const rect = el.getBoundingClientRect();
    return { x: rect.x, y: rect.y };
  }));
  expect(bounds[0].y).toBe(bounds[1].y);
  expect(bounds[1].y).toBe(bounds[2].y);
  expect(bounds[0].x).toBeLessThan(bounds[1].x);
  expect(bounds[1].x).toBeLessThan(bounds[2].x);
  await page.getByRole('button', { name: '立即执行每日灾情摘要', exact: true }).click();
  await expect(page.locator('.axn-chat-page')).toBeVisible();
  await expect(page.locator('.axn-task-card').last()).toContainText('已完成', { timeout: 30000 });
  await expect(page.locator('.axn-gs-conversation.is-active')).toContainText('每日灾情摘要');
  await page.getByRole('button', { name: '我的文件', exact: true }).click();
  const tab = page.getByRole('tab', { name: /态势感知智能体 / });
  await tab.focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('.axn-file-row', { hasText: '汇总灾情摘要' })).toBeVisible();
  await page.getByRole('button', { name: '定时任务', exact: true }).click();
  await page.reload();
  const card = page.locator('.axn-schedule-card', { hasText: '每日灾情摘要' });
  await expect(card).toBeVisible();
  await expect(card).not.toContainText('上次执行');
  await expect(page.getByRole('button', { name: /执行记录/ })).toHaveCount(0);
  await expect(page.getByRole('alert')).toHaveCount(0);
});

test('回答反馈支持点赞、原因补充、修改、撤回与刷新保留', async ({ page }) => {
  await page.goto('/');
  await page.locator('.axn-question-item').first().click();
  const feedback = page.getByRole('group', { name: '回答反馈', exact: true }).last();
  await expect(feedback).toBeVisible({ timeout: 30000 });
  await feedback.getByRole('button', { name: '有帮助', exact: true }).click();
  await expect(feedback.getByRole('button', { name: '有帮助', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.reload();
  await expect(feedback.getByRole('button', { name: '有帮助', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await feedback.getByRole('button', { name: '没帮助', exact: true }).click();
  const modal = page.getByRole('dialog');
  await modal.getByRole('button', { name: '提交反馈', exact: true }).click();
  await expect(modal).toContainText('请选择原因或填写补充说明');
  await modal.getByRole('checkbox', { name: '内容不准确', exact: true }).check();
  await modal.getByLabel('补充说明（选填）', { exact: true }).fill('请补充现场核实的依据。');
  await modal.getByRole('button', { name: '提交反馈', exact: true }).click();
  await expect(feedback.getByRole('button', { name: '没帮助', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(feedback.getByRole('button', { name: '有帮助', exact: true })).toHaveAttribute('aria-pressed', 'false');
  await page.reload();
  await feedback.getByRole('button', { name: '没帮助', exact: true }).click();
  await expect(modal.getByRole('checkbox', { name: '内容不准确', exact: true })).toBeChecked();
  await expect(modal.getByLabel('补充说明（选填）', { exact: true })).toHaveValue('请补充现场核实的依据。');
  await modal.getByRole('button', { name: '撤回反馈', exact: true }).click();
  await expect(feedback.getByRole('button', { name: '没帮助', exact: true })).toHaveAttribute('aria-pressed', 'false');
});
